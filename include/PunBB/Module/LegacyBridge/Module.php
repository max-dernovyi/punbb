	public function name(): string {
		return 'LegacyBridge';
	}

	/** The modules whose services, contracts and events the bridge serves, plugs and observes. */
	public function dependencies(): array {
		return array('Framework', 'Layout', 'Database', 'Site', 'Message', 'Help', 'Userlist', 'AdminIndex', 'Delete', 'Index', 'Reports', 'Reindex', 'Viewforum', 'Prune', 'Extern', 'Censoring', 'Ranks', 'Bans', 'Edit', 'Viewtopic', 'Categories', 'Login', 'Register', 'Post', 'Misc', 'Extensions', 'Search', 'Forums', 'Groups', 'Users', 'Moderate', 'Settings', 'Profile', 'Setup');
	}

	/** The installer and the updater are deleted once they have run; the bridge only serves them while they are there. */
