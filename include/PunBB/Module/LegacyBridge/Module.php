/**
 * The v2.0 bridge to what was written for the legacy core: extension code
 * stored for eval($hook), and pages and themes built on $tpl_main. It also
 * serves the core what the legacy bootstrap holds: the connection, the
 * visitor, the settings, the language packs and the URL scheme. Nothing else
