	/** @param array<string, string|list<string>> $covered */
	public function __construct(private readonly array $covered = self::COVERED) {}

	/** What covers $point, the first of them for an id fired at two sites; null when nothing does. */
	public function coveredBy(string $point): ?string {
		return $this->covering($point)[0] ?? null;
	}

	/** @return list<string> everything that covers $point, each at a site of its own */
	public function covering(string $point): array {
		$covered = $this->covered[$point] ?? array();

		return is_array($covered) ? $covered : array($covered);
	}
